const FONT_ADV = 5.7, FONT_SX = 4 / 3;   // advance in u units; glyphs are drawn a third wider than their grid

// Width of a string in local units at a given size (includes the italic lean of the last glyph).
function textWidth(str, size = 1) { return ((String(str).length - 1) * FONT_ADV + 3 * FONT_SX + 3) * size; }

// Build a shape for a string. (x, y) is the baseline start (left) unless o.align = 'center' | 'right'.
// o.w: stroke width in local units (default scales with size). o.show: number of glyphs visible (typing).
function textShape(str, x, y, size = 1, o = {}) {
  str = String(str).toUpperCase();
  const w = o.w ?? Math.max(.62, .7 * size), wid = textWidth(str, size);
  const x0 = o.align === 'center' ? x - wid / 2 : o.align === 'right' ? x - wid : x;
  const shapes = [], n = Math.min(str.length, o.show ?? str.length);
  for (let c = 0; c < n; c++) {
    const g = GLYPHS[str[c]] ?? GLYPHS['?'];
    for (const pl of g) shapes.push(Shape.stroke(pl.map(([u, v]) => [x0 + (c * FONT_ADV + u * FONT_SX + v / 2) * size, y - v * H * size]), w));
  }
  return shapes.length ? Shape.union(...shapes) : null;
}

// Paint text with a pen. Returns the pen.
function text(p, str, x, y, size, col, o = {}) {
  const s = textShape(str, x, y, size, o);
  if (s) p.fill(s, col, o);
  return p;
}
